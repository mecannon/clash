# ----------------------------------------------------------------
def shade(g,pal):
    H=len(g);W=len(g[0]);out=[r[:] for r in g]
    def at(x,y):return g[y][x] if 0<=x<W and 0<=y<H else '.'
    for y in range(H):
        for x in range(W):
            c=g[y][x]
            if c not in pal or not isinstance(pal[c],dict):continue
            edge_br=at(x+1,y) in 'o.' or at(x,y+1) in 'o.'
            edge_tl=at(x-1,y) in 'o.' or at(x,y-1) in 'o.'
            deep=(at(x+1,y) in 'o.' and at(x,y+1) in 'o.')
            if deep:out[y][x]=c+'d'
            elif edge_br and not edge_tl:out[y][x]=c+'s'
            elif edge_tl and not edge_br and (x<W*0.62 and y<H*0.7):out[y][x]=c+'h'
            elif edge_br:out[y][x]=c+'s'
            else:out[y][x]=c+'b'
    # second band: one pixel in from the bottom-right shadow edge on the lower half
    for y in range(H):
        for x in range(W):
            c=out[y][x]
            if len(c)==2 and c[1]=='b' and y>H*0.45:
                n=out[y+1][x] if y+1<H else '.'
                if len(n)==2 and n[1] in 'sd' and (x+1<W and len(out[y][x+1])==2 and out[y][x+1][1] in 'sd'):out[y][x]=c[0]+'s'
    return out
def color(c,pal):
    if c=='.':return None
    if len(c)==2:return pal[c[0]][c[1]]
    v=pal.get(c);return v['b'] if isinstance(v,dict) else v
def grid(id,d,fr=0):
    M=MONS[id];g=[list(r) for r in M[d]];g=shade(g,M['pal'])
    if fr==1:# bob: everything above the feet line drops 1px
        f=M['feet'];top=g[:f];g=[['.']*32]+top[:-1]+g[f:]
        g=g[:32]
    return [[color(c,M['pal']) for c in r] for r in g]
def render(ids,out='mp.png',sc=5):
    cols=[(d,f) for d in ('down','up','left') for f in (0,1)]
    im=Image.new('RGB',(len(cols)*34*sc,len(ids)*34*sc),(150,170,140))
    for r,id in enumerate(ids):
        for c,(d,f) in enumerate(cols):
            g=grid(id,d,f)
            for y in range(32):
                for x in range(32):
                    if g[y][x]:
                        for yy in range(sc):
                            for xx in range(sc):im.putpixel(((c*34+1+x)*sc+xx,(r*34+1+y)*sc+yy),hx(g[y][x]))
    im.save(out)
