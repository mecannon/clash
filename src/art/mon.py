def hx(c):return tuple(int(c[i:i+2],16) for i in (1,3,5))
def mix(a,b,k):a,b=hx(a),hx(b);return '#%02x%02x%02x'%tuple(round(a[i]*(1-k)+b[i]*k) for i in range(3))
def ramp(base,shade=None,deep=None,hi=None):
    return dict(b=base,s=shade or mix(base,'#1c1030',.34),d=deep or mix(base,'#1c1030',.6),h=hi or mix(base,'#fff4dc',.38))
def sym(rows):
    for r in rows: assert len(r)==16,(len(r),r)
    return [r+r[::-1] for r in rows]
def full(rows):
    for r in rows: assert len(r)==32,(len(r),r)
    return rows
